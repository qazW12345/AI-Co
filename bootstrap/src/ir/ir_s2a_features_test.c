/* Compare the builder's dump to the hand-computed oracle byte-for-byte.
 * On mismatch, print both dumps and the first differing line so the
 * drift can be analyzed (oracle remediation per the 16c1c precedent). */
static bool dump_matches_oracle(const char *case_name, const DiagBuf *actual,
                                const char *oracle, size_t oracle_len)
{
    size_t i;
    if (actual->len == oracle_len &&
        (oracle_len == 0 || memcmp(actual->data, oracle, oracle_len) == 0)) {
        return true;
    }
    fprintf(stderr, "\n=== ORACLE MISMATCH: %s ===\n", case_name);
    fprintf(stderr, "  oracle length %zu, actual length %zu\n",
            oracle_len, actual->len);
    /* first differing byte */
    for (i = 0; i < actual->len && i < oracle_len; i++) {
        if (actual->data[i] != oracle[i]) {
            break;
        }
    }
    {
        size_t ls = 0, le = 0;
        size_t as = 0, ae = 0;
        size_t j;
        for (j = 0; j < i; j++) {
            if (oracle[j] == '\n') { ls = j + 1; }
            if (actual->data[j] == '\n') { as = j + 1; }
        }
        for (j = i; j < oracle_len && oracle[j] != '\n'; j++) { le = j; }
        for (j = i; j < actual->len && actual->data[j] != '\n'; j++) { ae = j; }
        fprintf(stderr, "  first diff at byte %zu:\n", i);
        fprintf(stderr, "  oracle:  %.*s\n", (int)(le - ls + 1), oracle + ls);
        fprintf(stderr, "  actual:  %.*s\n", (int)(ae - as + 1), actual->data + as);
    }
    fprintf(stderr, "--- ORACLE (expected) ---\n%.*s\n", (int)oracle_len, oracle);
    fprintf(stderr, "--- ACTUAL (builder dump) ---\n%.*s\n",
            (int)actual->len, actual->data);
    return false;
}

/* Run the full per-case verification (acceptance criterion 7):
 * pipeline clean -> build OK -> cause finalize OK -> ir_core_verify
 * IR_OK (0 AIC-I0501) -> dump byte-identical to oracle ->
 * ir_dump_verify (invariant 12 round-trip). */
static void verify_case(const char *case_name, const char *src,
                        const char *oracle, size_t oracle_len)
{
    Pipeline p;
    IrBuild *b = NULL;
    IrBuilderStatus bs;
    DiagRecord **recs = NULL;
    size_t nrecs = 0;
    DiagBuf d;
    size_t i;

    CHECK(pipeline_accepted(&p, src));
    if (!pipeline_accepted(&p, src)) {
        pipeline_free(&p);
        return;
    }
    bs = pipeline_ir_build(&p, &b);
    CHECK(bs == IR_BUILDER_OK);
    CHECK(b != NULL);
    if (bs != IR_BUILDER_OK || b == NULL) {
        pipeline_free(&p);
        return;
    }
    CHECK(ir_core_verify(b, &recs, &nrecs) == IR_OK);
    if (nrecs > 0) {
        for (i = 0; i < nrecs && i < 5; i++) {
            fprintf(stderr, "  %s: AIC-I0501: %s\n", case_name,
                    recs[i] && recs[i]->message ? recs[i]->message
                                                : "(no message)");
        }
    }
    CHECK(nrecs == 0);
    ir_records_free(recs, nrecs);
    recs = NULL;
    nrecs = 0;

    diag_buf_init(&d);
    CHECK(ir_dump_write(b, &d));
    CHECK(dump_matches_oracle(case_name, &d, oracle, oracle_len));

    CHECK(ir_dump_verify(b, &recs, &nrecs) == IR_OK);
    CHECK(nrecs == 0);
    ir_records_free(recs, nrecs);
    recs = NULL;
    nrecs = 0;

    diag_buf_free(&d);
    ir_build_free(b);
    pipeline_free(&p);
}

